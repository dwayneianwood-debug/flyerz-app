"""Detect likely AI-generated images and choose print defaults.

The client hands over a picture. This module decides whether it looks like
generator artwork (ChatGPT, Midjourney, Flux and similar sizes or tags) and
which press defaults to pre-select. Nothing here blocks the job, and every
choice can be overridden.

Illustrator .ai / .eps intake is intentionally not handled here.
"""

