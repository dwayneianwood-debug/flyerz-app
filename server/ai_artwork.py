def check_text(path: str, spell_fn: Optional[SpellFn] = None) -> dict:
    """Flag suspicious wording. Never raises and never blocks the job."""
    fn = spell_fn if spell_fn is not None else (_SPELL or _default_spell)
    try:
        result = fn(path) or {}
    except Exception as exc:
        return {
            "text_status": "unavailable",
            "text_warnings": [],
            "text_message": "Text check could not run, so give any wording a quick look. The job was not stopped.",
            "blocked": False,
            "detail": str(exc)[:160],
        }
    if result.get("stub") or result.get("success") is False:
        return {
            "text_status": "unavailable",
            "text_warnings": [],
            "text_message": "Text check could not run, so give any wording a quick look. The job was not stopped.",
            "blocked": False,
        }
    raw = result.get("errors_found") or result.get("errors") or []
    warnings = []
    if isinstance(raw, list):
        for item in raw:
            if not isinstance(item, dict):
                continue
            word = str(item.get("word") or "").strip()
            suggestion = str(item.get("suggestion") or "").strip()
            if word:
                warnings.append({"word": word[:80], "suggestion": suggestion[:80]})
    if warnings:
        shown = "; ".join(
            f"'{item['word']}' → '{item['suggestion']}'" if item["suggestion"] else f"'{item['word']}'"
            for item in warnings[:6]
        )
        message = f"Possible text problem: {shown}. The job was not stopped."
        status = "warning"
    else:
        message = "Text check found nothing suspicious."
        status = "clear"
    return {
        "text_status": status,
        "text_warnings": warnings,
        "text_message": message,
        "blocked": False,
    }


def _effective_dpi(px_w: int, px_h: int, trim_w: float, trim_h: float) -> int:
    from ai_upscale import effective_print_dpi
    return int(effective_print_dpi(px_w, px_h, trim_w, trim_h, 5.0))


def _bleed_choice(bgr: np.ndarray) -> tuple[str, dict]:
    cmyk = sample_edge_cmyk(bgr)
    edge = {"c": cmyk[0], "m": cmyk[1], "y": cmyk[2], "k": cmyk[3]}
    if edge_std(bgr) <= FLAT_EDGE_STD:
        return "colourBorder", edge
    return "mirror", edge


def build_note(applied: list[str], text_message: str, bright_message: str) -> str:
    body = "; ".join(applied)
    parts = [f"AI-generated artwork detected. Auto-applied: {body}."]
    if text_message:
        parts.append(text_message)
    if bright_message:
        parts.append(bright_message)
    parts.append("You can change any of these.")
    return " ".join(parts)


def plan_artwork(path: str, trim_w_mm: float, trim_h_mm: float, options: Optional[dict] = None) -> dict:
    """Full recommendation for one image. Safe to call when the file is not AI."""
    options = options or {}
    bgr = cv2.imread(path, cv2.IMREAD_COLOR)
    if bgr is None:
        return {"success": True, "detected": False, "blocked": False, "message": "This file is not a picture we can check."}

    found = detect_ai_artwork(path, bgr)
    if not found["detected"]:
        return {"success": True, "detected": False, "blocked": False, "src_w": found["src_w"], "src_h": found["src_h"]}

    trim_w = float(trim_w_mm or 148)
    trim_h = float(trim_h_mm or 210)
    mismatch = ratios_differ(found["src_w"], found["src_h"], trim_w, trim_h)
    bleed, edge = _bleed_choice(bgr)
    dpi_now = _effective_dpi(found["src_w"], found["src_h"], trim_w, trim_h)
    enhance = dpi_now < TARGET_DPI
    fit = "crop" if mismatch else "none"
    offset = 0.5

    if mismatch and options.get("fit") in ("crop", "extend", "border"):
        fit = options["fit"]
    if options.get("offset") is not None:
        try:
            offset = max(0.0, min(1.0, float(options["offset"])))
        except (TypeError, ValueError):
            offset = 0.5
    if options.get("bleed") in ("mirror", "colourBorder", "replicate", "stretch", "bgExtract"):
        bleed = options["bleed"]
    if options.get("use_given_enhance"):
        enhance = bool(options.get("enhance"))

    reuse = options.get("reuse_text")
    if isinstance(reuse, dict) and reuse.get("text_message"):
        text = {
            "text_status": reuse.get("text_status") or "unavailable",
            "text_warnings": reuse.get("text_warnings") or [],
            "text_message": reuse.get("text_message") or "",
            "blocked": False,
        }
    else:
        text = check_text(path)

    hot = bright_rgb_fraction(bgr) >= 0.008
    bright_message = ""
    if hot:
        bright_message = (
            "Some bright screen colours will look duller in print. "
            "The preview is approximate — the press file still uses the FOGRA39 CMYK conversion."
        )

    screen_path = str(options.get("screen_preview") or "")
    print_path = str(options.get("print_preview") or "")
    source_path = str(options.get("source_preview") or "")
    if screen_path and print_path:
        try:
            screen, proof = make_soft_proof(bgr)
            save_png_300(screen, screen_path)
            save_png_300(proof, print_path)
        except Exception:
            pass
    if source_path:
        try:
            long_edge = max(bgr.shape[:2])
            shown = bgr
            if long_edge > 900:
                scale = 900.0 / float(long_edge)
                shown = cv2.resize(
                    bgr,
                    (max(1, int(round(bgr.shape[1] * scale))), max(1, int(round(bgr.shape[0] * scale)))),
                    interpolation=cv2.INTER_AREA,
                )
            save_png_300(shown, source_path)
        except Exception:
            pass

    applied: list[str] = []
    if mismatch and fit == "crop":
        applied.append("crop to fit, with the safe zone shown")
    elif mismatch and fit == "extend":
        if expand_is_configured() or _EXPAND is not None:
            applied.append("extend the background to the page shape, using AI expand when it returns a larger picture")
        else:
            applied.append("extend the background to the page shape on this computer")
    elif mismatch and fit == "border":
        applied.append("colour border matched to the edge colour to fill the page shape")
    elif not mismatch:
        applied.append("page shape already matches the print size")

    if bleed == "colourBorder":
        applied.append("Colour Border bleed matched to the edge colour")
    elif bleed == "mirror":
        applied.append("Mirror bleed, because the edges look photographic")
    else:
        applied.append(f"{bleed} bleed")

    if enhance:
        applied.append(f"AI Enhance on, because the picture is about {dpi_now} DPI at this print size (under 300)")
    else:
        applied.append(f"AI Enhance left off, because the picture is about {dpi_now} DPI at this print size")
    applied.append("CMYK conversion for litho print")

    note = build_note(applied, text["text_message"], bright_message)
    crop = cover_crop_box(found["src_w"], found["src_h"], trim_w, trim_h, offset)
    return {
        "success": True,
        "detected": True,
        "blocked": False,
        "reasons": found["reasons"],
        "src_w": found["src_w"],
        "src_h": found["src_h"],
        "dpi": found["dpi"],
        "mismatch": mismatch,
        "fit": fit if mismatch else "none",
        "offset": offset,
        "crop": crop,
        "bleed": bleed,
        "edge": edge,
        "edge_flat": edge_std(bgr) <= FLAT_EDGE_STD,
        "enhance": enhance,
        "effective_dpi": dpi_now,
        "bright": hot,
        "bright_message": bright_message,
        "text_status": text["text_status"],
        "text_warnings": text["text_warnings"],
        "text_message": text["text_message"],
        "applied": applied,
        "note": note,
    }


def configured_expand(path: str) -> dict:
    """Call expand_background only when a token or a test hook is present."""
    if _EXPAND is not None:
        return _EXPAND(path)
    if not expand_is_configured():
        return {
            "success": True,
            "stub": True,
            "enhanced_path": path,
            "message": "Background expansion requires API configuration. Your original artwork is preserved.",
        }
    return _default_expand(path)


def expand_is_configured() -> bool:
    try:
        from ai_enhancements import _get_replicate_token
        return bool(_get_replicate_token())
    except Exception:
        return False
